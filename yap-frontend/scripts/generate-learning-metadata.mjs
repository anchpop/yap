// Run after wasm-pack build. Generates static data for the web and the WASM-free MCP widget.
import { readFileSync, writeFileSync } from 'node:fs';
import * as glue from '../../yap-frontend-rs/pkg/yap_frontend_rs_bg.js';
const { instance } = await WebAssembly.instantiate(
  readFileSync(new URL('../../yap-frontend-rs/pkg/yap_frontend_rs_bg.wasm', import.meta.url)),
  { './yap_frontend_rs_bg.js': glue },
);
glue.__wbg_set_wasm(instance.exports);
instance.exports.__wbindgen_start();
const source = readFileSync(new URL('../src/lib/languages.ts', import.meta.url), 'utf8');
const languages = [...source.matchAll(/^  (\w+): \{/gm)].map(match => match[1]);
const metadata = Object.fromEntries(languages.map(language => [language, glue.get_language_learning_metadata(language)]));
const output = `// Generated by pnpm generate:metadata after rebuilding WASM. Do not edit.\nimport type { Language, LanguageLearningMetadata } from "../../../yap-frontend-rs/pkg";\n\nexport const LANGUAGE_LEARNING_METADATA = ${JSON.stringify(metadata, null, 2)} as const satisfies Record<Language, LanguageLearningMetadata>;\n`;
const path = new URL('../src/lib/learning-metadata.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Learning metadata is stale. Run pnpm generate:metadata after rebuilding WASM.');
} else {
  writeFileSync(path, output);
}
